	private function section( array $fields, array $extension_fields = array() ): array {
		return Wpml_Config::section(
			array(
				'acme/example' => array(
					'title'            => 'Example',
					'fields'           => $fields,
					'extension_fields' => $extension_fields,
				),
			)
		);
	}

	private function declared_paths( array $fields, array $extension_fields = array() ): array {
		$xml  = simplexml_load_string( Wpml_Config::document( $this->section( $fields, $extension_fields )['xml'] ) );
		$root = $xml->xpath( '/wpml-config/gutenberg-blocks/gutenberg-block/key[@name="blockstudio"]/key[@name="attributes"]' );

		return array() === $root ? array() : $this->key_paths( $root[0], '' );
	}

	private function key_paths( SimpleXMLElement $parent, string $path ): array {
		$paths = array();

		foreach ( $parent->key as $key ) {
			$name = $path . (string) $key['name'];

			if ( 0 === count( $key->key ) ) {
				$paths[] = $name;
				continue;
			}

			$paths = array_merge( $paths, $this->key_paths( $key, $name . '/' ) );
		}

		return $paths;
	}

	private function builder_declared_paths( array $attributes, string $path ): array {
		$paths = array();

		foreach ( $attributes as $key => $attribute ) {
			if ( empty( $attribute['blockstudio'] ) ) {
				continue;
			}

			$name  = $path . ( $attribute['id'] ?? $key );
			$field = $attribute['field'] ?? '';

			if ( in_array( $field, array( 'text', 'textarea', 'richtext', 'wysiwyg' ), true ) ) {
				$paths[] = $name;
			} elseif ( 'link' === $field ) {
				$paths[] = $name . '/title';
				$paths[] = $name . '/url';
			} elseif ( 'files' === $field ) {
				$paths[] = empty( $attribute['multiple'] ) ? $name : $name . '/*';
			} elseif ( 'repeater' === $field ) {
				$paths = array_merge( $paths, $this->builder_declared_paths( $attribute['attributes'] ?? array(), $name . '/*/' ) );
			}
		}

		return $paths;
	}
