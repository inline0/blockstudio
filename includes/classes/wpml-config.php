<?php
/**
 * WPML configuration class.
 *
 * @package Blockstudio
 */

namespace Blockstudio;

use DOMDocument;
use DOMElement;
use DOMXPath;
use WP_Error;

/**
 * Generates the WPML language configuration for Blockstudio blocks.
 *
 * WPML translates the attributes of a custom block only when a wpml-config.xml
 * declares them. A block without an entry is left to WPML's automatic string
 * detection, which offers every string attribute for translation, including
 * select values, file names, and URLs. This class declares the text fields of
 * every registered Blockstudio block and declares blocks without text fields
 * with translate="0". Files fields are declared as attachment IDs, which WPML
 * converts to the attachments of the page language on render, in blocks with
 * and without text fields.
 *
 * Fields are read from the registered block definitions, after custom field
 * expansion, attribute filters, overrides, and matching extensions. Keys follow
 * the storage rules of the attribute builder: Blockstudio stores every value
 * under blockstudio.attributes, fields in a group with an ID are prefixed with
 * that ID, groups without an ID and tabs add no level, and repeater rows are
 * matched with "*".
 *
 * A storage key can be defined more than once. Each definition is classified
 * as text (text, textarea, richtext, wysiwyg), link, files, repeater, or a
 * value that is not declared (every other built-in type, hidden fields, and
 * fields with "translate": false, which also applies to every field inside a
 * group, tabs, or repeater that sets it):
 *
 * - Within the fields of the block, outside repeater rows, the attribute
 *   builder registers one attribute per storage key, and a later definition
 *   replaces an earlier one.
 *   The fields of the matching extensions resolve the same way, in
 *   registration order, as Block::extension_attributes() and
 *   Extensions::render_blocks() do, so the field of a later extension
 *   replaces that of an earlier one.
 * - A block field and an extension field with the same storage key both
 *   apply: Block::render() gives the template the block's definition, and
 *   Extensions::render_blocks() uses the extension's.
 * - Two fields with the same ID in the rows of one repeater both apply as
 *   well: the attribute builder keeps both row definitions, Block::render()
 *   transforms a row value with the first, and the editor fills a new row
 *   with the default of the last.
 *
 * Definitions that both apply are declared once when they classify the same,
 * with the label of the first one (the block's field), and repeaters are
 * compared row field by row field. When they classify differently, the stored
 * value can be text, an option, or a link object, depending on the control
 * that wrote it, so the key is not declared and section() reports it as a
 * conflict. Text, textarea, richtext, and wysiwyg fields all store a string
 * and get the same declaration (WPML chooses the editor for each string from
 * its content), so they never conflict with each other. Files fields with and
 * without multiple both store attachment IDs and do not conflict either.
 *
 * Nothing here runs on a regular request: the configuration is generated on
 * demand by `wp bs wpml config`.
 *
 * @since 7.7.4
 */
final class Wpml_Config {

	/**
	 * Comment that opens the generated section in a wpml-config.xml file.
	 *
	 * @var string
	 */
	public const START = '<!-- blockstudio:start -->';

	/**
	 * Comment that closes the generated section in a wpml-config.xml file.
	 *
	 * @var string
	 */
	public const END = '<!-- blockstudio:end -->';

	/**
	 * Explanation written below the start marker.
	 *
	 * @var string
	 */
	private const NOTE = '<!-- Generated by wp bs wpml config. Run it again after changing block fields; edits between the markers are replaced. -->';

	/**
	 * Field types whose value is text an editor writes.
	 *
	 * @var array<int, string>
	 */
	private const TEXT_TYPES = array( 'text', 'textarea', 'richtext', 'wysiwyg' );

	/**
	 * Built-in field types whose value is not text to translate.
	 *
	 * WPML copies these values into the translation unchanged.
	 *
	 * @var array<int, string>
	 */
	private const VALUE_TYPES = array(
		'attributes',
		'block',
		'checkbox',
		'classes',
		'code',
		'color',
		'date',
		'datetime',
		'gradient',
		'html-tag',
		'icon',
		'number',
		'radio',
		'range',
		'select',
		'toggle',
		'token',
		'unit',
	);

	/**
	 * Collect the fields of every registered Blockstudio block.
	 *
	 * Fields that extensions add to a Blockstudio block are stored in the same
	 * attributes object, so they are included, separately from the block's own
	 * fields. Extensions of core or third-party blocks are not: an entry for
	 * those blocks would compete with the configuration that WPML or the
	 * block's plugin ships.
	 *
	 * @return array<string, array{title: string, fields: array, extension_fields: array}> Blocks by name, sorted by
	 *         name, with the block's fields and the fields of every matching extension in registration order.
	 */
	public static function registered_blocks(): array {
		$blocks = array();

		foreach ( Build::blocks() as $name => $block ) {
			$name = (string) $name;

			$blocks[ $name ] = array(
				'title'            => is_string( $block->title ?? null ) ? $block->title : '',
				'fields'           => is_array( $block->blockstudio['attributes'] ?? null )
					? array_values( $block->blockstudio['attributes'] )
					: array(),
				'extension_fields' => array_values( \bs_block_extension_fields( $name ) ),
			);
		}

		ksort( $blocks, SORT_STRING );

		return $blocks;
	}

	/**
	 * Build the generated section of a wpml-config.xml file.
	 *
	 * The section starts with START and ends with END. Between them, every
	 * block gets one gutenberg-block element: translate="1" with a key for each
	 * text field, or translate="0" when it has none. Keys for the attachment IDs
	 * of files fields are added in both cases.
	 *
	 * Example:
	 *
	 *     $section = Wpml_Config::section( Wpml_Config::registered_blocks() );
	 *     echo Wpml_Config::document( $section['xml'] );
	 *
	 * A storage key that a block field and an extension field both define, or
	 * that two fields define in the rows of one repeater, is declared only when
	 * the definitions classify the same; otherwise it is listed in conflicts,
	 * for example "acme/card: tone (text in the block, select in an
	 * extension)". See the class description for the full policy.
	 *
	 * @param array<string, array{title?: string, fields?: array, extension_fields?: array}> $blocks Blocks by name, as
	 *        returned by registered_blocks().
	 *
	 * @return array{xml: string, translated: int, untranslated: int, skipped: array<int, string>, conflicts: array<int, string>}
	 *         The section for a gutenberg-blocks element, the number of blocks with and without text fields, the fields
	 *         left out because their type is unknown, and the storage keys left out because their definitions conflict.
	 */
	public static function section( array $blocks ): array {
		$lines        = array( self::START, "\t\t" . self::NOTE );
		$skipped      = array();
		$conflicts    = array();
		$translated   = 0;
		$untranslated = 0;

		foreach ( $blocks as $name => $block ) {
			$name       = (string) $name;
			$fields     = self::inherit_translate( is_array( $block['fields'] ?? null ) ? $block['fields'] : array() );
			$extensions = self::inherit_translate( is_array( $block['extension_fields'] ?? null ) ? $block['extension_fields'] : array() );
			$candidates = self::combine(
				self::latest( self::definitions( $fields, 'block' ) ),
				self::latest( self::definitions( $extensions, 'extension' ) )
			);
			$keys       = self::keys( $candidates, $name, '', $skipped, $conflicts );
			$type       = 'type="' . self::escape( $name ) . '"';

			if ( array() === $keys ) {
				++$untranslated;
				$lines[] = "\t\t<gutenberg-block {$type} translate=\"0\" />";
				continue;
			}

			// WPML reads ID keys whatever translate says, so a block without text keeps translate="0".
			if ( self::has_text( $keys ) ) {
				++$translated;
				$title   = isset( $block['title'] ) && '' !== $block['title'] ? $block['title'] : $name;
				$lines[] = "\t\t<gutenberg-block {$type} translate=\"1\" label=\"" . self::escape( $title ) . '">';
			} else {
				++$untranslated;
				$lines[] = "\t\t<gutenberg-block {$type} translate=\"0\">";
			}

			$lines   = array_merge(
				$lines,
				self::render(
					array(
						array(
							'name' => 'blockstudio',
							'keys' => array(
								array(
									'name' => 'attributes',
									'keys' => $keys,
								),
							),
						),
					),
					3
				)
			);
			$lines[] = "\t\t</gutenberg-block>";
		}

		$lines[] = "\t\t" . self::END;

		return array(
			'xml'          => implode( "\n", $lines ),
			'translated'   => $translated,
			'untranslated' => $untranslated,
			'skipped'      => $skipped,
			'conflicts'    => $conflicts,
		);
	}

	/**
	 * Wrap a generated section in a complete wpml-config.xml document.
	 *
	 * @param string $section Section from section().
	 *
	 * @return string The document, without a trailing newline.
	 */
	public static function document( string $section ): string {
		return implode(
			"\n",
			array(
				'<wpml-config>',
				"\t<gutenberg-blocks>",
				"\t\t" . $section,
				"\t</gutenberg-blocks>",
				'</wpml-config>',
			)
		);
	}

	/**
	 * Replace the generated section of an existing wpml-config.xml file.
	 *
	 * Only the text from START to END changes, so every other section and
	 * entry of the file stays byte for byte as it is.
	 *
	 * @param string $contents Current file contents.
	 * @param string $section  Section from section().
	 *
	 * @return string|WP_Error The new contents, or an error when the file does not contain each marker exactly once.
	 */
	public static function merge( string $contents, string $section ) {
		$start = strpos( $contents, self::START );
		$end   = strpos( $contents, self::END );

		if (
			false === $start ||
			false === $end ||
			$end < $start ||
			1 !== substr_count( $contents, self::START ) ||
			1 !== substr_count( $contents, self::END )
		) {
			return new WP_Error(
				'blockstudio_wpml_config_markers',
				sprintf(
					'The file has no Blockstudio section. Add the lines %1$s and %2$s once inside its gutenberg-blocks element, then run the command again.',
					self::START,
					self::END
				)
			);
		}

		return substr( $contents, 0, $start ) . $section . substr( $contents, $end + strlen( self::END ) );
	}

	/**
	 * Check the structure of a wpml-config.xml document.
	 *
	 * WPML accepts one gutenberg-blocks element directly inside wpml-config,
	 * and gutenberg-block elements only inside it.
	 *
	 * @param string $xml Document.
	 *
	 * @return array<int, string>|WP_Error Block types declared more than once, or an error when the document is not a valid configuration.
	 */
	public static function validate( string $xml ) {
		$document = new DOMDocument();
		$previous = libxml_use_internal_errors( true );
		$loaded   = $document->loadXML( $xml, LIBXML_NONET );
		libxml_clear_errors();
		libxml_use_internal_errors( $previous );

		// phpcs:ignore WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase -- DOM property.
		if ( ! $loaded || 'wpml-config' !== $document->documentElement?->nodeName ) {
			return new WP_Error( 'blockstudio_wpml_config_invalid', 'The result is not a well-formed wpml-config document.' );
		}

		$xpath    = new DOMXPath( $document );
		$sections = $xpath->query( '/wpml-config/gutenberg-blocks' );
		$entries  = $xpath->query( '/wpml-config/gutenberg-blocks/gutenberg-block' );
		$all      = $xpath->query( '//gutenberg-block' );

		if ( false === $sections || false === $entries || false === $all || 1 !== $sections->length || $entries->length !== $all->length ) {
			return new WP_Error( 'blockstudio_wpml_config_invalid', 'The markers must be inside the single gutenberg-blocks element of the file.' );
		}

		$counts = array();

		foreach ( $entries as $entry ) {
			if ( $entry instanceof DOMElement ) {
				$type            = $entry->getAttribute( 'type' );
				$counts[ $type ] = ( $counts[ $type ] ?? 0 ) + 1;
			}
		}

		return array_keys( array_filter( $counts, static fn( int $count ): bool => $count > 1 ) );
	}

	/**
	 * Collect every definition of each storage key in a list of fields.
	 *
	 * Storage keys follow Container_Field_Handler: a group with an ID prefixes
	 * the IDs of its fields, a group without an ID and tabs add no level.
	 * Repeater rows are collected on their own level by keys(). Everything inside
	 * a hidden group or tabs field counts as hidden.
	 *
	 * @param array             $fields  Field definitions, in the order Blockstudio reads them.
	 * @param string            $source  Where the fields come from: "block" or "extension".
	 * @param string            $prefix  Storage key prefix from the enclosing groups with an ID.
	 * @param array<int,string> $parents Labels of the enclosing repeaters and groups with an ID.
	 * @param bool              $hidden  Whether an enclosing group or tabs field is hidden.
	 *
	 * @return array<string, array<int, array{field: array, source: string, parents: array<int,string>, hidden: bool}>>
	 *         The definitions of each storage key in order, with the keys in the order they first appear.
	 */
	private static function definitions( array $fields, string $source, string $prefix = '', array $parents = array(), bool $hidden = false ): array {
		return Field_Definitions::collect( $fields, $source, $prefix, $parents, $hidden );
	}

	/**
	 * Keep the last definition of each storage key.
	 *
	 * Outside repeater rows, the attribute builder writes each attribute by
	 * storage key, so a later definition replaces an earlier one, whatever its
	 * type. The same holds for the fields of several extensions, which
	 * Block::extension_attributes() and Extensions::render_blocks() merge in
	 * registration order. Repeater rows keep every definition (see keys()).
	 *
	 * @param array<string, array<int, array>> $definitions Definitions from definitions().
	 *
	 * @return array<string, array<int, array>> The last definition of each storage key.
	 */
	private static function latest( array $definitions ): array {
		return Field_Definitions::latest( $definitions );
	}

	/**
	 * Add the definitions of a second list to those of a first, key by key.
	 *
	 * @param array<string, array<int, array>> $definitions Definitions by storage key.
	 * @param array<string, array<int, array>> $more        Definitions to add after them.
	 *
	 * @return array<string, array<int, array>> Both, with the keys of the first list first.
	 */
	private static function combine( array $definitions, array $more ): array {
		return Field_Definitions::combine( $definitions, $more );
	}

	/**
	 * Build the key nodes for the definitions that apply to each storage key.
	 *
	 * Definitions of one key that classify differently (see kind()) are
	 * reported as a conflict and not declared. Otherwise text fields become a
	 * key, link fields a key with title and url, files fields a key with
	 * type="post-ids" and sub-type="attachment" (on a level "*" when one of the
	 * definitions has multiple), repeaters a key with one row
	 * level matched with "*" (the row fields of all its definitions compared the
	 * same way), and value fields nothing. The first definition, the block's own
	 * where there is one, gives the label. Where the attribute builder stores
	 * nothing, for a group with an ID nested in another group or in repeater
	 * rows, the key matches no value and WPML ignores it.
	 *
	 * @param array<string, array<int, array>> $candidates Definitions that apply to each storage key, as from definitions().
	 * @param string                           $block      Block name, for the skipped and conflicts lists.
	 * @param string                           $path       Storage path of the enclosing repeater rows, empty outside them:
	 *                                                     each repeater adds its key and "*", separated by slashes.
	 * @param array<int,string>                $skipped    Fields of unknown types (passed by reference).
	 * @param array<int,string>                $conflicts  Storage keys whose definitions conflict (passed by reference).
	 *
	 * @return array<int, array> Key nodes.
	 */
	private static function keys( array $candidates, string $block, string $path, array &$skipped, array &$conflicts ): array {
		$nodes = array();

		foreach ( $candidates as $key => $entries ) {
			$key   = (string) $key;
			$kinds = array_values( array_unique( array_map( static fn( array $entry ): string => self::kind( $entry ), $entries ) ) );

			if ( 1 !== count( $kinds ) ) {
				$conflicts[] = sprintf( '%1$s: %2$s (%3$s)', $block, $path . $key, self::describe( $entries ) );
				continue;
			}

			$field   = $entries[0]['field'];
			$parents = $entries[0]['parents'];
			$label   = implode( ': ', array_merge( $parents, array( self::label( $field, (string) $field['id'] ) ) ) );
			$context = array(
				'block'   => $block,
				'path'    => $path . $key,
				'field'   => $field,
				'parents' => $parents,
			);

			if ( 'repeater' === $kinds[0] ) {
				$rows = array();

				foreach ( $entries as $entry ) {
					$inner = is_array( $entry['field']['attributes'] ?? null ) ? $entry['field']['attributes'] : array();
					$trail = array_merge( $entry['parents'], array( self::label( $entry['field'], (string) $entry['field']['id'] ) ) );
					$rows  = self::combine( $rows, self::definitions( Field_Definitions::children( $inner ), $entry['source'], '', $trail ) );
				}

				$rows = self::keys( $rows, $block, $path . $key . '/*/', $skipped, $conflicts );

				if ( array() !== $rows ) {
					$nodes[] = array(
						'name' => $key,
						'keys' => array(
							array(
								'name' => '*',
								'keys' => $rows,
							),
						),
					);
				}
				continue;
			}

			if ( 'text' === $kinds[0] ) {
				$nodes[] = array(
					'name'  => $key,
					'label' => self::filter_label( $label, $context + array( 'part' => 'text' ) ),
				);
			} elseif ( 'link' === $kinds[0] ) {
				// WPML points a URL declared as a link to the translated page when it saves a translation.
				$nodes[] = array(
					'name' => $key,
					'keys' => array(
						array(
							'name'  => 'title',
							/* translators: %s: Label of a link field, preceded by the labels of its enclosing repeaters and groups. */
							'label' => self::filter_label( sprintf( __( '%s: Link text', 'blockstudio' ), $label ), $context + array( 'part' => 'title' ) ),
						),
						array(
							'name'  => 'url',
							'type'  => 'link',
							/* translators: %s: Label of a link field, preceded by the labels of its enclosing repeaters and groups. */
							'label' => self::filter_label( sprintf( __( '%s: URL', 'blockstudio' ), $label ), $context + array( 'part' => 'url' ) ),
						),
					),
				);
			} elseif ( 'files' === $kinds[0] ) {
				// A multiple field stores a list, or the ID itself when one file is selected. WPML converts both under "*".
				$ids     = array(
					'type'     => 'post-ids',
					'sub-type' => 'attachment',
				);
				$nodes[] = self::multiple( $entries )
					? array(
						'name' => $key,
						'keys' => array( array( 'name' => '*' ) + $ids ),
					)
					: array( 'name' => $key ) + $ids;
			} elseif ( 'value' !== $kinds[0] ) {
				$skipped[] = sprintf( '%1$s: %2$s (%3$s)', $block, $label, (string) $field['type'] );
			}
		}

		return $nodes;
	}

	/**
	 * Pass "translate": false from groups, tabs, and repeaters to the fields inside them.
	 *
	 * Groups and tabs add no definition of their own, and the rows of a
	 * repeater are classified field by field, so the setting has to reach
	 * every field below the container that sets it.
	 *
	 * @param array $fields    Field definitions.
	 * @param bool  $inherited Whether an enclosing container sets "translate": false.
	 *
	 * @return array The field definitions, with "translate": false on every field below such a container.
	 */
	private static function inherit_translate( array $fields, bool $inherited = false ): array {
		foreach ( $fields as $index => $field ) {
			if ( ! is_array( $field ) ) {
				continue;
			}

			$off = $inherited || false === ( $field['translate'] ?? null );

			if ( $off ) {
				$field['translate'] = false;
			}

			if ( is_array( $field['attributes'] ?? null ) ) {
				$field['attributes'] = self::inherit_translate( $field['attributes'], $off );
			}

			if ( is_array( $field['tabs'] ?? null ) ) {
				foreach ( $field['tabs'] as $tab_index => $tab ) {
					if ( is_array( $tab['attributes'] ?? null ) ) {
						$field['tabs'][ $tab_index ]['attributes'] = self::inherit_translate( $tab['attributes'], $off );
					}
				}
			}

			$fields[ $index ] = $field;
		}

		return $fields;
	}

	/**
	 * Classify a definition by the declaration its stored value needs.
	 *
	 * @param array{field: array, source: string, parents: array<int,string>, hidden: bool} $entry Definition.
	 *
	 * @return string "text", "link", "files", "repeater", "value" for a value that is not declared, or "type:" followed
	 *                by the type for an unknown type.
	 */
	private static function kind( array $entry ): string {
		$type = (string) $entry['field']['type'];

		// Hidden fields hold values that editors do not write, such as block field references.
		if ( $entry['hidden'] || false === ( $entry['field']['translate'] ?? null ) || in_array( $type, self::VALUE_TYPES, true ) ) {
			return 'value';
		}

		if ( in_array( $type, self::TEXT_TYPES, true ) ) {
			return 'text';
		}

		return in_array( $type, array( 'link', 'files', 'repeater' ), true ) ? $type : 'type:' . $type;
	}

	/**
	 * Check whether one of the definitions of a files field allows several files.
	 *
	 * @param array<int, array{field: array, source: string, parents: array<int,string>, hidden: bool}> $entries Definitions.
	 *
	 * @return bool Whether one of them has multiple.
	 */
	private static function multiple( array $entries ): bool {
		foreach ( $entries as $entry ) {
			if ( ! empty( $entry['field']['multiple'] ) ) {
				return true;
			}
		}

		return false;
	}

	/**
	 * Check whether key nodes declare text, that is any key other than attachment IDs.
	 *
	 * @param array<int, array> $nodes Key nodes.
	 *
	 * @return bool Whether one of the keys is text.
	 */
	private static function has_text( array $nodes ): bool {
		foreach ( $nodes as $node ) {
			if ( empty( $node['keys'] ) ? 'post-ids' !== ( $node['type'] ?? '' ) : self::has_text( $node['keys'] ) ) {
				return true;
			}
		}

		return false;
	}

	/**
	 * Describe the definitions of a conflicting storage key.
	 *
	 * @param array<int, array{field: array, source: string, parents: array<int,string>, hidden: bool}> $entries Definitions.
	 *
	 * @return string Types by source, for example "text in the block, select in an extension".
	 */
	private static function describe( array $entries ): string {
		$types = array();

		foreach ( $entries as $entry ) {
			$where             = 'block' === $entry['source'] ? 'in the block' : 'in an extension';
			$prefix            = $entry['hidden'] ? 'hidden ' : ( false === ( $entry['field']['translate'] ?? null ) ? 'untranslated ' : '' );
			$types[ $where ][] = $prefix . (string) $entry['field']['type'];
		}

		$parts = array();

		foreach ( $types as $where => $list ) {
			$parts[] = implode( ' and ', array_unique( $list ) ) . ' ' . $where;
		}

		return implode( ', ', $parts );
	}

	/**
	 * Render key nodes as indented XML lines.
	 *
	 * @param array<int, array> $nodes Key nodes.
	 * @param int               $depth Indentation depth in tabs.
	 *
	 * @return array<int, string> Lines.
	 */
	private static function render( array $nodes, int $depth ): array {
		$lines  = array();
		$indent = str_repeat( "\t", $depth );

		foreach ( $nodes as $node ) {
			$attributes = ' name="' . self::escape( $node['name'] ) . '"';

			foreach ( array( 'type', 'sub-type', 'label' ) as $attribute ) {
				if ( isset( $node[ $attribute ] ) && '' !== $node[ $attribute ] ) {
					$attributes .= ' ' . $attribute . '="' . self::escape( $node[ $attribute ] ) . '"';
				}
			}

			if ( empty( $node['keys'] ) ) {
				$lines[] = "{$indent}<key{$attributes} />";
				continue;
			}

			$lines[] = "{$indent}<key{$attributes}>";
			$lines   = array_merge( $lines, self::render( $node['keys'], $depth + 1 ) );
			$lines[] = "{$indent}</key>";
		}

		return $lines;
	}

	/**
	 * Get the label of a field for the translation editor.
	 *
	 * @param array  $field Field definition.
	 * @param string $id    Field ID, used when the field has no label.
	 *
	 * @return string Label.
	 */
	private static function label( array $field, string $id ): string {
		return Field_Definitions::label( $field, $id );
	}

	/**
	 * Filter the label of a generated key.
	 *
	 * @param string $label   Label.
	 * @param array  $context Block name, storage path, field definition, parent labels, and part, see the filter.
	 *
	 * @return string The filtered label, or the label when the filter returns something other than a string.
	 */
	private static function filter_label( string $label, array $context ): string {
		/**
		 * Filter the label of a key in the configuration generated by `wp bs wpml config`.
		 *
		 * WPML shows the label as the field name in its translation editor. Return
		 * an empty string to leave the label out, so WPML falls back to the label
		 * of the block.
		 *
		 * @since 7.7.6
		 * @param string $label   Label: the field label, preceded by the labels of the enclosing
		 *                        repeaters and groups with an ID, and for link fields followed by
		 *                        the translated suffix of the part.
		 * @param array  $context {
		 *     Key context.
		 *
		 *     @type string            $block   Block name.
		 *     @type string            $path    Storage path of the field below blockstudio.attributes,
		 *                                      with a level "*" for the rows of each repeater, separated
		 *                                      by slashes.
		 *     @type array             $field   Field definition.
		 *     @type array<int,string> $parents Labels of the enclosing repeaters and groups with an ID.
		 *     @type string            $part    "text" for a text field, "title" or "url" for the parts of a link field.
		 * }
		 */
		$filtered = apply_filters( 'blockstudio/wpml/config/label', $label, $context );

		return is_string( $filtered ) ? $filtered : $label;
	}

	/**
	 * Escape a value for an XML attribute.
	 *
	 * @param string $value Value.
	 *
	 * @return string Escaped value.
	 */
	private static function escape( string $value ): string {
		return htmlspecialchars( $value, ENT_QUOTES | ENT_XML1 | ENT_SUBSTITUTE, 'UTF-8' );
	}
